"""Summarise download throughput vs number of parallel streams from
data/logs/download_timing.csv -> results/download_throughput.md (+ .csv).
  python scripts/throughput_report.py [--where "Mac, Ulaanbaatar-area home link"]
"""
import argparse, sys
from pathlib import Path
import pandas as pd
REPO = Path(__file__).resolve().parents[1]
ap = argparse.ArgumentParser(); ap.add_argument("--where", default="this machine"); a = ap.parse_args()
d = pd.read_csv(REPO / "data/logs/download_timing.csv")
d = d[d.status == "ok"]
rows = []
for tag, g in d.groupby("tag", sort=False):
    span = g.finished.max() - (g.finished.min() - g.seconds[g.finished.idxmin()])
    rows.append(dict(tag=tag, streams=int(g.streams.iloc[0]), station_days=len(g), GB=g.bytes.sum() / 1e9,
                     MB_per_s_total=g.bytes.sum() / 1e6 / span, s_per_request_median=g.seconds.median(),
                     MB_per_s_per_stream=(g.bytes / g.seconds).median() / 1e6,
                     MB_per_station_day=g.bytes.mean() / 1e6))
r = pd.DataFrame(rows)
r.to_csv(REPO / "results/download_throughput.csv", index=False)
txt = (f"# Download throughput (EarthScope FDSN dataselect, XL HH?, one request per station-day)\n\n"
       f"Measured on {a.where}. Generated by `scripts/throughput_report.py` from `data/logs/download_timing.csv`.\n\n"
       + r.to_markdown(index=False, floatfmt=".2f") + "\n")
(REPO / "results/download_throughput.md").write_text(txt); print(txt)
