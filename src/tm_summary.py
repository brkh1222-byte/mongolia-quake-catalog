"""Summarise template-matching detections against the catalogue.

For each template, the self-detection (highest network sum, equal to the number
of channels) fixes the offset between detection time and the origin time of the
template event. Every detection then gets an estimated origin time
(detect_time - offset). Detections with a negative network sum (anticorrelated)
are dropped. Detections of different templates within 2 s of each other are
merged, keeping the one with the highest mean correlation per channel. A
detection is "catalogued" if its estimated origin is within 3 s of a catalogue
origin, otherwise "new".

Output: data/catalogs/{tag}/templates/detections_summary.csv and a markdown
fragment results/template_matching_{tag}.md

Example
  python src/tm_summary.py --tag pilot_2013-01
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import glob

import numpy as np
import pandas as pd

from common import base_parser, load_config, path, to_epoch


def main(argv=None):
    ap = base_parser(__doc__)
    ap.add_argument("--tag", required=True)
    args = ap.parse_args(argv)
    cfg = load_config(args.config)
    d = path(cfg, "catalogs") / args.tag
    cat = pd.read_csv(d / "events.csv").sort_values("time").reset_index(drop=True)
    files = sorted(glob.glob(str(d / "templates" / "detections" / "*.csv")))
    det = pd.concat([pd.read_csv(f) for f in files if Path(f).stat().st_size > 5], ignore_index=True)
    det["t"] = to_epoch(det.detect_time)
    det["cc_mean"] = det.detect_val / det.no_chans
    n_raw = len(det)
    det = det[det.detect_val > 0].copy()
    tcat = cat.time.to_numpy()
    offs = {}
    for name, g in det.groupby("template"):
        s = g.loc[g.cc_mean.idxmax()]
        if s.cc_mean < 0.95:
            continue  # no clean self-detection
        k = int(np.argmin(np.abs(tcat - s.t)))
        if abs(tcat[k] - s.t) < 120:
            offs[name] = (s.t - tcat[k], cat.event_id[k], cat.ml.get(k, np.nan) if "ml" in cat else np.nan)
    det = det[det.template.isin(offs)].copy()
    det["origin_est"] = det.t - det.template.map(lambda n: offs[n][0])
    det["template_event"] = det.template.map(lambda n: offs[n][1])
    det = det.sort_values("origin_est").reset_index(drop=True)
    keep, last = [], -1e18
    for i, r in det.iterrows():  # merge detections within 2 s
        if r.origin_est - last <= 2.0 and keep:
            if r.cc_mean > det.cc_mean[keep[-1]]:
                keep[-1] = i
        else:
            keep.append(i)
        last = r.origin_est
    u = det.loc[keep].copy()
    u["dt_cat"] = [float(np.min(np.abs(tcat - x))) for x in u.origin_est]
    u["self"] = u.cc_mean > 0.95
    u["catalogued"] = u.dt_cat <= 3.0
    u.to_csv(d / "templates" / "detections_summary.csv", index=False)
    new = u[~u.catalogued]
    L = [f"### Template matching: {args.tag}", "",
         f"- Days scanned: {len(files)}; templates with a clean self-detection: {len(offs)}.",
         f"- Raw detections: {n_raw}; with positive network correlation: {int((det.detect_val > 0).sum())}; after merging "
         f"detections within 2 s: {len(u)}.",
         f"- Of these, {int(u.self.sum())} are the templates themselves, {int((u.catalogued & ~u.self).sum())} are other "
         f"catalogued events, and **{len(new)} are new** (no catalogue origin within 3 s).",
         f"- New detections by mean correlation per channel: ≥ 0.5: {int((new.cc_mean >= 0.5).sum())}; 0.3–0.5: "
         f"{int(((new.cc_mean >= 0.3) & (new.cc_mean < 0.5)).sum())}; < 0.3: {int((new.cc_mean < 0.3).sum())}. "
         f"Median detection-to-threshold ratio of new detections: {float((new.detect_val / new.threshold).median()) if len(new) else float('nan'):.2f}.",
         f"- Catalogue events of quality A–C in the scanned days: {int((cat.quality != 'D').sum())}; a gain of "
         f"{100 * len(new) / max(int((cat.quality != 'D').sum()), 1):.0f} % in event count if all new detections are real.",
         "", "New detections are not located and have no magnitude yet; those near the threshold need visual checks.",
         "", "Generated by `src/tm_summary.py`."]
    (path(cfg, "results") / f"template_matching_{args.tag}.md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
