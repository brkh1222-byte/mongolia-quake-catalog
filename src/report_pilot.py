"""Assemble results/validation_month.md from the outputs of the pilot steps.

Inputs (all produced by other scripts; missing pieces are reported as missing):
  data/picks/raw/*, data/picks/ensemble/*          src/pick.py, src/ensemble.py
  data/catalogs/{tag}/events.csv, picks.parquet     src/associate.py, src/locate.py, src/magnitude.py
  data/catalogs/{tag}/events_dd2020.csv             src/locate.py --vmodel config/vmodel_dashdondog2020.yaml
  results/quakescope_{tag}.md                       src/compare_quakescope.py
  results/validation_{tag}_refs.md / .csv           src/validate.py
  results/{tag}/summary.csv                         src/analyze.py --pilot
  data/logs/pick_timing.csv, results/download_throughput.md

Example
  python src/report_pilot.py --tag pilot_2013-01 --start 2013-01-01 --end 2013-02-01 --stations HD
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import numpy as np
import pandas as pd
from obspy import UTCDateTime

from common import base_parser, days, load_config, path, select_stations

DD2020_EVENTS, DD2020_MONTHS = 12912, 22  # Dashdondog et al. 2020: Jun 2012 – Apr 2014, manual picks


def count_raw(cfg, stations, start, end):
    from pick import raw_pick_path

    rows = []
    for spec in cfg["picking"]["models"]:
        n = {"P": 0, "S": 0}
        nfiles = 0
        n03 = 0
        for t in days(start, end):
            for sta in stations.station:
                f = raw_pick_path(cfg, spec["model"], spec["weights"], "XL", sta, t)
                if f.exists():
                    nfiles += 1
                    df = pd.read_parquet(f)
                    for ph in ("P", "S"):
                        n[ph] += int((df.phase == ph).sum())
                    n03 += int((df.prob >= 0.3).sum())
        rows.append(dict(model=spec["model"], weights=spec["weights"], station_days=nfiles, P=n["P"], S=n["S"],
                         picks_p_ge_0p3=n03, per_station_day=(n["P"] + n["S"]) / max(nfiles, 1)))
    return pd.DataFrame(rows)


def main(argv=None):
    ap = base_parser(__doc__)
    from ensemble import add_ensemble_args

    add_ensemble_args(ap)
    ap.add_argument("--tag", required=True)
    args = ap.parse_args(argv)
    from ensemble import apply_ensemble_args

    cfg = apply_ensemble_args(load_config(args.config), args)
    res = path(cfg, "results")
    d = path(cfg, "catalogs") / args.tag
    st = select_stations(cfg, args.stations or "HD", args.start, args.end)
    ndays = len(days(args.start, args.end))
    L = [f"# Pilot validation: {args.tag}", "",
         f"**What this is:** a methods check of the full pipeline on one month ({args.start} to {args.end}, "
         f"exclusive) of the Hangay subarray ({len(st)} stations operating). It is not a scientific result: Mc, b and D90 "
         "from one month are dominated by sampling noise and are reported only to show that the code works end to end.",
         "", "Generated by `src/report_pilot.py`; every number below is computed from files in `data/` and `results/`.", ""]

    # 1. data
    avail = path(cfg, "logs") / "availability.csv"
    if avail.exists():
        a = pd.read_csv(avail)
        a = a[a.station.isin(st.station) & (a.day >= args.start) & (a.day < args.end)]
        z = a[a.channel.str.endswith("Z")].groupby(["station", "day"]).seconds.sum()
        nod = path(cfg, "logs") / "nodata.csv"
        nn = 0
        if nod.exists():
            nd = pd.read_csv(nod)
            nn = int(((nd.day >= args.start) & (nd.day < args.end) & nd.station.isin(st.station)).sum())
        L += ["## 1. Data", "",
              f"- Station-days possible: {len(st) * ndays}; downloaded with data: {len(z)}; reported empty by the data centre: {nn}.",
              f"- Mean fraction of the day covered (vertical channel): {np.mean(np.clip(z / 86400, 0, 1)):.3f}.",
              f"- Total raw volume: {a.drop_duplicates(['station', 'day']).bytes.sum() / 1e9:.1f} GB.", ""]
    thr = res / "download_throughput.md"
    if thr.exists():
        L += ["Download throughput on the Mac (see `results/download_throughput.md`):", "",
              "\n".join(thr.read_text().splitlines()[4:]), ""]

    # 2. picks
    raw = count_raw(cfg, st, args.start, args.end)
    L += ["## 2. Picks", "", "Raw picks per model/weight pair (threshold 0.2):", "", raw.to_markdown(index=False, floatfmt=".1f"), ""]
    from associate import load_ensemble

    ens = load_ensemble(cfg, st, args.start, args.end)
    if len(ens):
        L += [f"Ensemble picks (≥{cfg['ensemble']['min_models']} of {len(cfg['picking']['models'])} pairs, mean prob ≥ "
              f"{cfg['ensemble']['min_mean_prob']}): **{len(ens)}** (P {int((ens.phase == 'P').sum())}, "
              f"S {int((ens.phase == 'S').sum())}); median support {ens.n_models.median():.0f} pairs; "
              f"median time spread across pairs {ens.time_std.median() * 1000:.0f} ms.", ""]
        sup = ens.n_models.value_counts().sort_index()
        L += ["Support distribution (number of pairs agreeing): " + ", ".join(f"{k}: {v}" for k, v in sup.items()), ""]
    tim = path(cfg, "logs") / "pick_timing.csv"
    if tim.exists():
        t = pd.read_csv(tim)
        t = t[(t.day >= args.start) & (t.day < args.end)]
        if len(t):
            L += [f"Picking time (all six pairs, device {t.device.iloc[-1]}): median {t.total_s.median():.1f} s per station-day "
                  f"over {len(t)} station-days.", ""]

    # 3. QuakeScope
    q = res / f"quakescope_{args.tag}.md"
    L += ["## 3. Picks compared with QuakeScope (Ni et al. 2025)", ""]
    L += ["\n".join(q.read_text().splitlines()[2:]) if q.exists() else "(not run)", ""]

    # 4. events
    if (d / "events.csv").exists():
        cat = pd.read_csv(d / "events.csv")
        qc = cat.quality.value_counts().reindex(list("ABCD"), fill_value=0)
        AB = cat[cat.quality.isin(["A", "B"])]
        L += ["## 4. Events (PyOcto association + least-squares location)", "",
              f"- Associated events: **{len(cat)}**; quality A {qc['A']}, B {qc['B']}, C {qc['C']}, D {qc['D']} "
              f"(D = rms > {cfg['location']['max_rms_s']} s or at the edge of the search volume, i.e. probably outside the network).",
              f"- Per day: {len(cat) / ndays:.0f} (all), {len(AB) / ndays:.0f} (A+B).",
              f"- Benchmark: the manual MNDC catalogue had {DD2020_EVENTS} events in {DD2020_MONTHS} months "
              f"(Dashdondog et al. 2020), i.e. ≈ {DD2020_EVENTS / DD2020_MONTHS:.0f} per month on average. "
              f"The pilot month has **{len(cat[cat.quality != 'D'])}** events of quality A–C "
              f"(**{len(cat[cat.quality != 'D']) / (DD2020_EVENTS / DD2020_MONTHS):.1f}×** that average). "
              "Seasonal and aftershock variation make this a rough comparison only. Meltzer et al. (2019) did not "
              "report their catalogue size.", ""]
        if len(AB):
            L += ["Location quality (A+B events): " + ", ".join([
                f"median rms {AB.rms_s.median():.2f} s", f"median erh {AB.erh_km.median():.1f} km",
                f"median erz {AB.erz_km.median():.1f} km", f"median gap {AB.gap_deg.median():.0f}°",
                f"median nearest station {AB.dmin_km.median():.0f} km",
                f"median {AB.n_picks.median():.0f} picks on {AB.n_sta.median():.0f} stations"]) + ".", ""]
            L += [f"Depth (A events, n={int((cat.quality == 'A').sum())}): median {cat[cat.quality == 'A'].depth_km.median():.1f} km, "
                  f"90th percentile {cat[cat.quality == 'A'].depth_km.quantile(0.9):.1f} km; fraction above 10 km "
                  f"{(cat[cat.quality == 'A'].depth_km < 10).mean():.2f}. "
                  "(Meltzer et al. 2019: upper 20 km, majority in the upper 10 km.)", ""]
            sh = 111.2 * np.hypot(AB.latitude - AB.pyocto_lat, (AB.longitude - AB.pyocto_lon) * np.cos(np.radians(AB.latitude)))
            L += [f"Shift between the PyOcto grid location and the least-squares location (A+B): median {sh.median():.1f} km "
                  f"horizontally, {np.median(np.abs(AB.depth_km - AB.pyocto_depth)):.1f} km in depth.", ""]
        if "ml" in cat and cat.ml.notna().any():
            m = cat.ml.dropna()
            L += [f"Magnitudes: ML for {len(m)} events, range {m.min():.1f} to {m.max():.1f}, median {m.median():.1f}.", ""]
        alt = d / "events_dd2020.csv"
        if alt.exists():
            b = pd.read_csv(alt)
            mm = cat.merge(b[["event_id", "latitude", "longitude", "depth_km", "quality"]], on="event_id", suffixes=("", "_dd"))
            mA = mm[(mm.quality == "A") & (mm.quality_dd == "A")]
            if len(mA):
                dz = mA.depth_km_dd - mA.depth_km
                dh = 111.2 * np.hypot(mA.latitude_dd - mA.latitude, (mA.longitude_dd - mA.longitude) * np.cos(np.radians(mA.latitude)))
                L += ["### Velocity-model sensitivity", "",
                      f"Relocating with the 8-layer South-Hangay model of Dashdondog et al. (2020) instead of the 2-layer model "
                      f"(events quality A in both, n={len(mA)}): depth change median {dz.median():+.1f} km "
                      f"(16–84 %: {dz.quantile(0.16):+.1f} to {dz.quantile(0.84):+.1f} km); horizontal shift median {dh.median():.1f} km. "
                      f"D90 2-layer {mA.depth_km.quantile(0.9):.1f} km vs Dashdondog {mA.depth_km_dd.quantile(0.9):.1f} km.", ""]

    # 5. reference bulletins
    r = res / f"validation_{args.tag}_refs.md"
    L += ["## 5. Events compared with ISC, EMSC and USGS", ""]
    L += [r.read_text() if r.exists() else "(not run)", ""]

    # 6. pilot statistics
    s = res / args.tag / "summary.csv"
    if s.exists():
        L += ["## 6. Pilot-only statistics (NOT results)", "", pd.read_csv(s).to_markdown(index=False), "",
              "Meltzer et al. (2019): Mc 1.2 (MAXC + 0.2), b 0.71, from the full 21-month preliminary catalogue.", ""]
    (res / "validation_month.md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
