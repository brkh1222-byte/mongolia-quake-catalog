"""Apply the T5.x analysis (src/analysis.py) to one catalog and write figures
and a summary table.

With --pilot every output is stamped "PILOT – NOT A RESULT": one month of data
is far too short for Mc, b-value or D90 to mean anything scientifically. The
pilot run only proves that the code works end to end.

Outputs (results/{tag}/):
  fig_map.png          epicentres coloured by depth, sized by ML, with stations
  fig_fmd.png          frequency–magnitude distribution with Mc and the b-value fit
  fig_depth.png        depth histograms per region with D90
  fig_section.png      depth section along a SW–NE profile through the Hangay
  fig_hourly.png       local-hour histogram (blast screening)
  summary.csv / summary.md

Example
  python src/analyze.py --tag pilot_2013-01 --pilot
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import numpy as np
import pandas as pd

import analysis as A
from common import REPO, base_parser, get_logger, load_config, path

STAMP = "PILOT – NOT A RESULT"


def main(argv=None):
    ap = base_parser(__doc__)
    ap.add_argument("--tag", required=True)
    ap.add_argument("--pilot", action="store_true")
    ap.add_argument("--min-quality", default="B", help="use events of this quality class or better")
    ap.add_argument("--faults", default=None, help="GeoJSON of fault traces (AFEAD)")
    args = ap.parse_args(argv)
    cfg = load_config(args.config)
    log = get_logger("analyze")
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    d = path(cfg, "catalogs") / args.tag
    cat = pd.read_csv(d / "events.csv")
    out = path(cfg, "results") / args.tag
    out.mkdir(parents=True, exist_ok=True)
    stamp = STAMP if args.pilot else ""
    regions = A.load_regions(REPO / "config" / "regions.geojson")
    cat["region"] = A.assign_regions(cat, regions)
    good = cat[cat.quality <= args.min_quality].copy()
    mag = "ml_corr" if "ml_corr" in cat and cat.ml_corr.notna().any() else "ml"
    good["ml"] = good[mag]
    flag, ratio, overall = A.blast_flags(good)
    good["blast_flag"] = flag
    rows = [dict(item="events (all qualities)", value=len(cat)),
            dict(item=f"events quality <= {args.min_quality}", value=len(good)),
            dict(item="magnitude column", value=mag),
            dict(item="day/night rate ratio (09–18 local solar time)", value=round(overall, 2)),
            dict(item="blast-flagged events", value=int(flag.sum()))]
    nat = good[~good.blast_flag & good.ml.notna()]
    mc1 = A.mc_maxc(nat.ml)
    mc2, lev, _ = A.mc_gof(nat.ml)
    rows += [dict(item="Mc (MAXC + 0.2)", value=mc1), dict(item=f"Mc (GOF {lev}%)", value=mc2)]
    bres = A.b_value(nat.ml, mc1) if np.isfinite(mc1) else {}
    rows += [dict(item="b (Aki–Utsu, at MAXC Mc)", value=bres.get("b")),
             dict(item="b 95% bootstrap", value=f"{bres.get('b_lo', np.nan):.2f}–{bres.get('b_hi', np.nan):.2f}"),
             dict(item="N >= Mc", value=bres.get("n"))]
    dsel = nat[nat.quality == "A"] if (nat.quality == "A").sum() >= 20 else nat
    for reg, g in dsel.groupby("region"):
        dp = A.depth_percentiles(g.depth_km)
        rows.append(dict(item=f"D90 {reg} (n={dp['n']}, quality {'A' if dsel is not nat else '<=' + args.min_quality})",
                         value=f"{dp.get('D90', np.nan):.1f} [{dp.get('D90_lo', np.nan):.1f}, {dp.get('D90_hi', np.nan):.1f}]"))
    summ = pd.DataFrame(rows)
    summ.to_csv(out / "summary.csv", index=False)
    (out / "summary.md").write_text(f"# {args.tag} analysis summary {('(' + stamp + ')') if stamp else ''}\n\n"
                                    + summ.to_markdown(index=False) + "\n\nGenerated by `src/analyze.py`.\n")
    log.info("\n%s", summ.to_string(index=False))

    st = pd.read_csv(path(cfg, "meta") / "stations.csv")
    # map
    fig, ax = plt.subplots(figsize=(8, 6.5))
    s_used = st[st.station.str[:2] == cfg["pilot"]["subarray"]] if args.pilot else st
    ax.scatter(s_used.lon, s_used.lat, marker="^", s=25, c="none", edgecolors="k", lw=0.6, label="stations")
    sc = ax.scatter(good.longitude, good.latitude, c=good.depth_km, s=4 + 6 * np.clip(good.ml.fillna(0), 0, 5) ** 1.5,
                    cmap="viridis_r", vmin=0, vmax=40, alpha=0.8, edgecolors="none")
    if flag.any():
        ax.scatter(good.longitude[flag], good.latitude[flag], marker="x", c="r", s=15, lw=0.7, label="blast flag")
    for name, poly in regions.items():
        x, y = poly.exterior.xy
        ax.plot(x, y, lw=0.6, ls="--", c="0.4")
    plt.colorbar(sc, ax=ax, label="depth (km)")
    ax.set_xlabel("Longitude (°E)"); ax.set_ylabel("Latitude (°N)")
    ax.set_aspect(1 / np.cos(np.radians(47)))
    ax.set_title(f"{args.tag}: {len(good)} events (quality ≤ {args.min_quality}) {stamp}", fontsize=9)
    ax.legend(fontsize=7, loc="lower right")
    fig.savefig(out / "fig_map.png", dpi=180, bbox_inches="tight"); plt.close(fig)
    # FMD
    bins, counts, cum = A.fmd(nat.ml)
    if len(bins):
        fig, ax = plt.subplots(figsize=(5.5, 4))
        ax.semilogy(bins, counts, "o", ms=3, mfc="none", label="non-cumulative")
        ax.semilogy(bins, cum, "s", ms=3, label="cumulative")
        if bres.get("b") and np.isfinite(bres["b"]):
            mm = bins[bins >= mc1 - 1e-9]
            ax.semilogy(mm, 10 ** (bres["a"] - bres["b"] * mm), "k-", lw=1,
                        label=f"b = {bres['b']:.2f} [{bres['b_lo']:.2f}, {bres['b_hi']:.2f}]")
            ax.axvline(mc1, color="r", lw=0.8, ls="--", label=f"Mc(MAXC+0.2) = {mc1:.1f}")
        ax.set_xlabel(f"{mag}"); ax.set_ylabel("N"); ax.legend(fontsize=7)
        ax.set_title(f"FMD {stamp}", fontsize=9)
        fig.savefig(out / "fig_fmd.png", dpi=180, bbox_inches="tight"); plt.close(fig)
    # depth histograms
    regs = [r for r in ["hangay_interior", "hangay_margin", "khovsgol", "gobi_altai"] if (dsel.region == r).any()]
    if regs:
        fig, axs = plt.subplots(1, len(regs), figsize=(3 * len(regs), 3.5), sharey=True, squeeze=False)
        for ax, r in zip(axs[0], regs):
            g = dsel[dsel.region == r]
            ax.hist(g.depth_km, bins=np.arange(-2, 45, 2), orientation="horizontal", color="0.6")
            dp = A.depth_percentiles(g.depth_km)
            if "D90" in dp:
                ax.axhline(dp["D90"], color="r", lw=1)
                ax.axhspan(dp["D90_lo"], dp["D90_hi"], color="r", alpha=0.15)
            ax.set_title(f"{r} (n={len(g)})", fontsize=8); ax.set_xlabel("N")
        axs[0][0].invert_yaxis(); axs[0][0].set_ylabel("depth (km)")
        fig.suptitle(f"Depth distributions, D90 ± 95% bootstrap {stamp}", fontsize=9)
        fig.savefig(out / "fig_depth.png", dpi=180, bbox_inches="tight"); plt.close(fig)
    # section SW->NE across the dome
    prof, L = A.profile_projection(good, 45.0, 96.5, 49.0, 103.0, half_width_km=40)
    fig, ax = plt.subplots(figsize=(8, 3))
    ax.scatter(prof.along_km, prof.depth_km, s=4, c="k")
    if "erz_km" in prof:
        ax.errorbar(prof.along_km, prof.depth_km, yerr=prof.erz_km.clip(upper=20), fmt="none", lw=0.3, c="0.5")
    ax.set_ylim(50, -3); ax.set_xlim(0, L)
    ax.set_xlabel("distance along profile 45.0°N 96.5°E → 49.0°N 103.0°E (km)"); ax.set_ylabel("depth (km)")
    ax.set_title(f"Depth section (±40 km) {stamp}", fontsize=9)
    fig.savefig(out / "fig_section.png", dpi=180, bbox_inches="tight"); plt.close(fig)
    # hourly
    h = A.local_hour(good.time.to_numpy(), good.longitude.to_numpy())
    fig, ax = plt.subplots(figsize=(5, 3))
    ax.hist(h, bins=np.arange(25), color="0.5")
    ax.axvspan(9, 18, color="orange", alpha=0.15, label="09–18 local solar time")
    ax.set_xlabel("local solar hour"); ax.set_ylabel("events"); ax.legend(fontsize=7)
    ax.set_title(f"Hour-of-day {stamp}", fontsize=9)
    fig.savefig(out / "fig_hourly.png", dpi=180, bbox_inches="tight"); plt.close(fig)
    if args.faults:
        dist, names = A.fault_distances(good, Path(args.faults))
        A.per_fault_stats(good, dist, names, mc=mc1).to_csv(out / "fault_stats.csv")
    good.to_csv(out / "events_analyzed.csv", index=False)


if __name__ == "__main__":
    main()
